function withoutApi(items: DefaultTheme.SidebarItem[]): DefaultTheme.SidebarItem[] {
  return items
    .filter((item) => !item.link?.startsWith('/ts/api/'))
    .map((item) => (item.items ? { ...item, items: withoutApi(item.items) } : item))
}

function mapValues(
  sidebar: DefaultTheme.SidebarMulti,
  map: (items: DefaultTheme.SidebarItem[]) => DefaultTheme.SidebarItem[],
) {
  return Object.fromEntries(
    Object.entries(sidebar).map(([path, items]) => [path, map(items as DefaultTheme.SidebarItem[])]),
  )
}
